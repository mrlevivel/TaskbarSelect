using System;
using System.Globalization;

namespace TaskbarSelect
{
    // Pure receipt, provenance and gesture fixtures. These checks never query
    // Explorer, create a helper/window, inject input, request UAC or touch a profile.
    internal static class TaskManagerShellIdentityTests
    {
        const string AppId = "Microsoft.AutoGenerated.{11111111-2222-4333-8444-555555555555}";
        const string OtherId = "Microsoft.AutoGenerated.{AAAAAAAA-BBBB-4CCC-8DDD-EEEEEEEEEEEE}";
        static readonly IntPtr Window = new IntPtr(101), Taskbar = new IntPtr(202);
        const uint Process = 303, ShellProcess = 404;
        const long Started = 638960100000000000, ShellStarted = 638960000000000000;

        internal static void Run(Action<bool, string> check)
        {
            Requests(check);
            Receipts(check);
            ProofBinding(check);
            Freshness(check);
            DirectTargets(check);
            NativeFallback(check);
            PhysicalGesture(check);
        }

        static string Number(long value) { return value.ToString(CultureInfo.InvariantCulture); }
        static string Receipt()
        { return "TSM1|" + Number(Window.ToInt64()) + "|" + Number(Process) + "|" + Number(Started) + "|" + AppId; }
        static bool Parse(string output, string error, int exitCode, out string identity)
        { return TaskManagerShellIdentity.ParseReceipt(output, error, exitCode, Window, Process, Started, out identity); }

        static void Requests(Action<bool, string> check)
        {
            IntPtr window; uint process; long started;
            var valid = new[] { "--read-task-manager-identity", Number(Window.ToInt64()), Number(Process), Number(Started) };
            check(TaskManagerShellIdentity.ParseRequest(valid, out window, out process, out started) &&
                window == Window && process == Process && started == Started,
                "The isolated read-only resolver request preserves the exact target HWND and process lifetime");
            foreach (string[] malformed in new[] {
                null, new string[0], new[] { valid[0], valid[1], valid[2] },
                new[] { valid[0], valid[1], valid[2], valid[3], "extra" },
                new[] { "--other-mode", valid[1], valid[2], valid[3] },
                new[] { valid[0], "0", valid[2], valid[3] },
                new[] { valid[0], "-1", valid[2], valid[3] },
                new[] { valid[0], "0101", valid[2], valid[3] },
                new[] { valid[0], "+101", valid[2], valid[3] },
                new[] { valid[0], "101 ", valid[2], valid[3] },
                new[] { valid[0], valid[1], "0", valid[3] },
                new[] { valid[0], valid[1], "4294967296", valid[3] },
                new[] { valid[0], valid[1], valid[2], "0" },
                new[] { valid[0], valid[1], valid[2], "-1" },
                new[] { valid[0], valid[1], valid[2], "9223372036854775808" }
            }) {
                check(!TaskManagerShellIdentity.ParseRequest(malformed, out window, out process, out started) &&
                    window == IntPtr.Zero && process == 0 && started == 0,
                    "Malformed resolver arguments fail closed without leaving a partially decoded target");
            }
        }

        static void Receipts(Action<bool, string> check)
        {
            string identity;
            check(Parse(Receipt(), "", 0, out identity) && identity == AppId &&
                Parse(Receipt() + "\r\n", "", 0, out identity) && identity == AppId &&
                Parse(Receipt() + "\n", "", 0, out identity) && identity == AppId,
                "A successful bounded single receipt proves the requested window identity with a normal terminal newline");
            foreach (string malformed in new[] {
                null, "", " " + Receipt(), Receipt() + " ", Receipt() + "|extra", Receipt() + "\nextra",
                Receipt() + "\r", Receipt() + "\n\n", Receipt() + "\r\n\r\n",
                Receipt().Replace("TSM1|", "TSM2|"), Receipt().Replace("TSM1|101|", "TSM1|0101|"),
                Receipt().Replace("TSM1|101|", "TSM1|+101|"), Receipt().Replace("|303|", "|0303|"),
                Receipt().Replace("|303|", "|0|"), Receipt().Replace(Number(Started), "0"),
                Receipt().Replace(Number(Started), "0" + Number(Started)),
                Receipt().Replace(AppId, "Task Manager"), Receipt().Replace(AppId, "Microsoft.Windows.TaskManager"),
                Receipt().Replace(AppId, AppId.ToLowerInvariant()), Receipt().Replace(AppId, AppId + ".suffix"),
                Receipt().Replace(AppId, AppId.Replace("11111111", "1111111Z")),
                Receipt().Replace(AppId, @"C:\Windows\System32\Taskmgr.exe"), new string('x', 257)
            }) {
                identity = "stale previous receipt";
                check(!Parse(malformed, "", 0, out identity) && String.IsNullOrEmpty(identity),
                    "Malformed, unbounded, decorated or unsupported resolver output never retains a usable identity");
            }
            check(!Parse(Receipt(), "resolver error", 0, out identity) && String.IsNullOrEmpty(identity) &&
                !Parse(Receipt(), "\r\n", 0, out identity) && String.IsNullOrEmpty(identity) &&
                !Parse(Receipt(), "", 1, out identity) && String.IsNullOrEmpty(identity),
                "A plausible identity cannot hide a resolver error or failed process exit");
            check(!TaskManagerShellIdentity.ParseReceipt(Receipt(), "", 0, new IntPtr(102), Process, Started, out identity) &&
                !TaskManagerShellIdentity.ParseReceipt(Receipt(), "", 0, Window, Process + 1, Started, out identity) &&
                !TaskManagerShellIdentity.ParseReceipt(Receipt(), "", 0, Window, Process, Started + 1, out identity),
                "A receipt for a different HWND, PID or process creation identity cannot bind to the requested target");
        }

        static void Freshness(Action<bool, string> check)
        {
            check(TaskManagerShellIdentity.ProofFreshAt(Proof(), 1000, 1000) &&
                TaskManagerShellIdentity.ProofFreshAt(Proof(), 3000, 1000) &&
                !TaskManagerShellIdentity.ProofFreshAt(Proof(), 3001, 1000),
                "Supplemental shell evidence expires after its two-second observation budget without extending a click deadline");
            check(!TaskManagerShellIdentity.ProofFreshAt(Proof(), 999, 1000) &&
                !TaskManagerShellIdentity.ProofFreshAt(Proof(), 1000, 0) &&
                !TaskManagerShellIdentity.ProofFreshAt(Proof(), 1000, -1) &&
                !TaskManagerShellIdentity.ProofFreshAt(null, 1000, 1000),
                "Future captures, unavailable timing frequency and absent shell snapshots fail closed");
            check(!TaskManagerShellIdentity.ProofFreshAt(Proof(Window, Process, Started, Taskbar, ShellProcess, ShellStarted, AppId, 0), 1000, 1000),
                "An uninitialized capture timestamp is not accepted as an old but real shell proof");
            check(TaskManagerShellIdentity.HoverProofFreshAt(true, Proof(), 1000, 1000) &&
                TaskManagerShellIdentity.HoverProofFreshAt(true, Proof(), 1500, 1000) &&
                !TaskManagerShellIdentity.HoverProofFreshAt(true, Proof(), 1501, 1000),
                "Background hover reuse expires at its own 500ms boundary rather than the broader proof lifetime");
            check(!TaskManagerShellIdentity.HoverProofFreshAt(false, Proof(), 1000, 1000) &&
                !TaskManagerShellIdentity.HoverProofFreshAt(false, Proof(), 1500, 1000),
                "A post-release verification always rereads shell identity even when the hover proof was captured this tick");
            check(!TaskManagerShellIdentity.HoverProofFreshAt(true, Proof(), 999, 1000) &&
                !TaskManagerShellIdentity.HoverProofFreshAt(true, Proof(), 1000, 0) &&
                !TaskManagerShellIdentity.HoverProofFreshAt(true, null, 1000, 1000),
                "A future, untimed or absent hover proof cannot be reused");
        }

        static TaskManagerShellIdentity.Proof Proof(IntPtr window, uint process, long started,
            IntPtr taskbar, uint shellProcess, long shellStarted, string appId, long captured)
        { return new TaskManagerShellIdentity.Proof(window, process, started, taskbar, shellProcess, shellStarted, appId, captured); }
        static TaskManagerShellIdentity.Proof Proof()
        { return Proof(Window, Process, Started, Taskbar, ShellProcess, ShellStarted, AppId, 1000); }
        static bool Matches(TaskManagerShellIdentity.Proof proof)
        { return TaskManagerShellIdentity.ProofMatchesTarget(proof, Window, Process, Started, Taskbar, AppId); }

        static void ProofBinding(Action<bool, string> check)
        {
            check(Matches(Proof()) && TaskManagerShellIdentity.ProofsMatch(Proof(), Proof()),
                "An exact shell-derived identity binds to the target and retains the Explorer process provenance");
            check(TaskManagerShellIdentity.ProofsMatch(Proof(), Proof(Window, Process, Started, Taskbar, ShellProcess, ShellStarted, AppId, 1050)),
                "Fresh verification may have a new capture time while still proving the same immutable target and shell identity");
            check(!Matches(null) && !TaskManagerShellIdentity.ProofsMatch(null, Proof()) &&
                !TaskManagerShellIdentity.ProofsMatch(Proof(), null),
                "Absent shell evidence cannot authorize direct Task Manager movement");
            foreach (TaskManagerShellIdentity.Proof changed in new[] {
                Proof(new IntPtr(102), Process, Started, Taskbar, ShellProcess, ShellStarted, AppId, 1050),
                Proof(Window, Process + 1, Started, Taskbar, ShellProcess, ShellStarted, AppId, 1050),
                Proof(Window, Process, Started + 1, Taskbar, ShellProcess, ShellStarted, AppId, 1050),
                Proof(Window, Process, Started, new IntPtr(203), ShellProcess, ShellStarted, AppId, 1050),
                Proof(Window, Process, Started, Taskbar, ShellProcess + 1, ShellStarted, AppId, 1050),
                Proof(Window, Process, Started, Taskbar, ShellProcess, ShellStarted + 1, AppId, 1050),
                Proof(Window, Process, Started, Taskbar, ShellProcess, ShellStarted, OtherId, 1050)
            }) {
                check(!TaskManagerShellIdentity.ProofsMatch(Proof(), changed),
                    "A target, shell lifetime or generated identity change between hover and release rejects the direct path");
            }
            check(!Matches(Proof(new IntPtr(102), Process, Started, Taskbar, ShellProcess, ShellStarted, AppId, 1000)) &&
                !Matches(Proof(Window, Process + 1, Started, Taskbar, ShellProcess, ShellStarted, AppId, 1000)) &&
                !Matches(Proof(Window, Process, Started + 1, Taskbar, ShellProcess, ShellStarted, AppId, 1000)) &&
                !Matches(Proof(Window, Process, Started, new IntPtr(203), ShellProcess, ShellStarted, AppId, 1000)) &&
                !Matches(Proof(Window, Process, Started, Taskbar, ShellProcess, ShellStarted, OtherId, 1000)),
                "No target field can be substituted when admitting a shell proof");
            check(!Matches(Proof(Window, Process, Started, Taskbar, 0, ShellStarted, AppId, 1000)) &&
                !Matches(Proof(Window, Process, Started, Taskbar, ShellProcess, 0, AppId, 1000)) &&
                !Matches(Proof(Window, 0, Started, Taskbar, ShellProcess, ShellStarted, AppId, 1000)) &&
                !Matches(Proof(Window, Process, 0, Taskbar, ShellProcess, ShellStarted, AppId, 1000)),
                "Unavailable target or Explorer process lifetimes cannot serve as a shell proof");
        }

        static readonly DateTime Now = new DateTime(2026, 10, 17, 15, 0, 0, DateTimeKind.Utc);
        static TaskbarTargets.Target Target()
        {
            TaskManagerShellIdentity.Proof proof = Proof();
            return new TaskbarTargets.Target {
                Button = new TaskbarMover.Click { AppId = AppId, AppName = "Task Manager", Taskbar = Taskbar,
                    ButtonBounds = new Native.Rect { Left = 0, Top = 0, Right = 40, Bottom = 40 } },
                Taskbar = Taskbar, Window = Window, Process = Process, ProcessStarted = Started, NeedsNativeSelection = true,
                ShellProof = proof, Captured = Now.AddMilliseconds(-100),
                Windows = new[] { new TaskbarTargets.WindowIdentity {
                    Window = Window, Process = Process, ProcessStarted = Started, NeedsNativeSelection = true, ShellProof = proof } }
            };
        }
        static void RejectTarget(Action<bool, string> check, Action<TaskbarTargets.Target> change, string reason)
        {
            TaskbarTargets.Target target = Target(); change(target);
            check(!TaskbarNativeSelection.DirectTargetShape(target), "Direct shell admission rejects " + reason);
        }
        static void DirectTargets(Action<bool, string> check)
        {
            check(TaskbarNativeSelection.DirectTargetShape(Target()),
                "A unique weak Task Manager target gains direct eligibility only with matching window-specific shell evidence");
            check(!TaskbarNativeSelection.DirectTargetShape(null), "A missing target cannot be intercepted");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.ShellProof = null; }, "an unavailable resolver proof");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Windows[0].ShellProof = null; }, "missing per-window shell evidence");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Windows[0].ShellProof = Proof(Window, Process, Started,
                Taskbar, ShellProcess, ShellStarted + 1, AppId, 1050); }, "a restarted Explorer between target and window snapshots");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Windows[0].ProcessStarted++; }, "a recycled Task Manager process");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Windows[0].NeedsNativeSelection = false; }, "a changed window-selection provenance");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Windows = null; }, "missing window resolution");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Windows = new TaskbarTargets.WindowIdentity[0]; }, "no unique window");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Windows = new[] { t.Windows[0], t.Windows[0] }; }, "an ambiguous window group");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Windows[0] = null; }, "a failed window snapshot");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Button.Grouped = true; }, "a grouped taskbar button");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Button.PreviewOnly = true; }, "a preview-only button");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Button.SelectionStarted = true; }, "a thumbnail-selection gesture");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Button.Taskbar = new IntPtr(203); }, "a changed taskbar origin");
            RejectTarget(check, delegate(TaskbarTargets.Target t) { t.Button.AppId = OtherId; }, "a copied but different generated identity");
            var ordinary = Target(); ordinary.NeedsNativeSelection = false; ordinary.ShellProof = null;
            ordinary.Windows[0].ShellProof = null;
            check(TaskbarNativeSelection.DirectTargetShape(ordinary),
                "Ordinary applications do not acquire a new shell-resolver dependency");
        }

        static void NativeFallback(Action<bool, string> check)
        {
            TaskbarTargets.Target origin = Target(), fresh = Target();
            fresh.ShellProof = fresh.Windows[0].ShellProof = null;
            check(TaskbarTargets.SameButton(origin, fresh) && TaskbarTargets.SameWindows(origin.Windows, fresh.Windows),
                "Losing optional shell evidence keeps the existing weak target identity and native-selection fallback available");
            var click = new TaskbarMover.Click { AppId = AppId, AppName = "Task Manager", Taskbar = Taskbar,
                Position = new TaskbarMover.Point { X = 20, Y = 20 }, PriorWindow = Window, PriorProcess = Process,
                NativeGesture = true, NativeDownTime = 1000, Time = Now.AddMilliseconds(-200), ReleasedAt = Now.AddMilliseconds(-150),
                Origin = origin, Verification = new TaskbarTargets.Probe { Complete = true, Result = fresh } };
            check(!TaskbarNativeSelection.DirectTargetShape(fresh) &&
                TaskbarNativeSelection.HasMinimizeProof(click, fresh, Window, true, 1200, Now),
                "A resolver miss still requires actual native minimize proof and can use the previously tested recovery path");
            check(!TaskbarNativeSelection.HasMinimizeProof(click, fresh, Window, false, 1200, Now),
                "A resolver miss cannot convert a plausible generated identity into direct movement");
            fresh.ShellProof = fresh.Windows[0].ShellProof = Proof(Window, Process, Started, Taskbar, ShellProcess + 1, ShellStarted + 1, AppId, 1050);
            check(TaskbarTargets.SameButton(origin, fresh) && TaskbarTargets.SameWindows(origin.Windows, fresh.Windows) &&
                !TaskManagerShellIdentity.ProofsMatch(origin.ShellProof, fresh.ShellProof),
                "A changed supplemental Explorer proof blocks direct reuse without changing the native fallback's own matching policy");
        }

        static bool Gesture(bool physicalDown, bool physicalUp, uint down, uint up, uint now, bool modified)
        {
            return TaskbarNativeSelection.DirectGestureAllowed(true, physicalDown, physicalUp, down, up, now, modified);
        }

        static void PhysicalGesture(Action<bool, string> check)
        {
            check(Gesture(true, true, 1000, 1100, 1150, false),
                "A fresh physical Task Manager click can use the proven direct path without waiting for a minimize event");
            check(!Gesture(false, true, 1000, 1100, 1150, false) &&
                !Gesture(true, false, 1000, 1100, 1150, false) &&
                !Gesture(false, false, 1000, 1100, 1150, false),
                "Injected input at either end cannot inherit a physical Task Manager fast-path gesture");
            check(TaskbarNativeSelection.IsPhysicalPointer(0) &&
                !TaskbarNativeSelection.IsPhysicalPointer(1) && !TaskbarNativeSelection.IsPhysicalPointer(2) &&
                !TaskbarNativeSelection.IsPhysicalPointer(3),
                "Both Windows injected-pointer flag forms remain excluded rather than treating a copied identity as input proof");
            check(!Gesture(true, true, 1000, 1100, 1150, true),
                "A modifier arriving before final direct admission preserves normal Windows behavior");
            check(Gesture(true, true, 1000, 1100, 1999, false) &&
                !Gesture(true, true, 1000, 1100, 2000, false),
                "Resolving and rechecking shell identity cannot extend the original Task Manager gesture beyond one second");
            check(!Gesture(true, true, 1000, 999, 1150, false) &&
                !Gesture(true, true, 1000, 1151, 1150, false) &&
                !Gesture(true, true, 1000, 1100, 999, false),
                "Queued pre-click releases, future releases and a backward gesture clock cannot authorize direct movement");
            check(Gesture(true, true, UInt32.MaxValue - 100, 0, 150, false) &&
                !Gesture(true, true, UInt32.MaxValue - 100, 0, 1000, false),
                "Native timestamp rollover admits a current physical click while preserving its original expiry");
            check(!Gesture(true, true, 1000, 1100, unchecked(1000U + 0x80000000U), false),
                "An ambiguous half-range tick delta fails closed");
            check(TaskbarNativeSelection.DirectGestureAllowed(false, false, false, 1000, 999, 4000, true),
                "The new Task Manager physical-input policy does not alter ordinary application admission");
        }
    }
}
