using System;

namespace TaskbarSelect
{
    // All checks are pure metadata/timing policies. No user window, UI Automation,
    // process creation, UAC, token changes, settings or Startup access.
    internal static class TaskbarNativeSelectionTests
    {
        const string Generated = "Microsoft.AutoGenerated.{11111111-2222-4333-8444-555555555555}";
        const string OtherGenerated = "Microsoft.AutoGenerated.{A337110D-3E9C-4169-B71F-2A6931BF81DE}";
        const string SystemPath = @"C:\Windows\System32\Taskmgr.exe";

        internal static void Run(Action<bool, string> check)
        {
            Identities(check);
            Metadata(check);
            Readability(check);
            Timing(check);
            NativeSelectionProof(check);
        }

        static void Identities(Action<bool, string> check)
        {
            check(TaskbarNativeSelection.IsGeneratedIdentity(Generated) && TaskbarNativeSelection.IsGeneratedIdentity(OtherGenerated),
                "Task Manager recovery accepts different canonical generated GUIDs without a machine-specific identity");
            foreach (string identity in new[] { null, "", "Taskmgr", "Microsoft.Windows.TaskManager", Generated + " ", " " + Generated,
                Generated.Replace("Microsoft.AutoGenerated.", "Other.AutoGenerated."),
                Generated.Replace("Microsoft.AutoGenerated.", "microsoft.autogenerated."),
                Generated.Replace("{", "").Replace("}", ""), Generated.Replace("11111111", "1111111Z"),
                Generated.Replace("{11111111-2222-4333-8444-555555555555}", "{11111111222243338444555555555555}"),
                Generated + ".Taskmgr", @"C:\Windows\System32\Taskmgr.exe" })
                check(!TaskbarNativeSelection.IsGeneratedIdentity(identity), "Malformed, explicit, path and noncanonical generated identities are not weak native-selection candidates");
            long started;
            check(!TaskbarNativeSelection.TryIdentifyTaskManager(null, IntPtr.Zero, out started) && started == 0 &&
                !TaskbarNativeSelection.TryIdentifyTaskManager(new TaskbarMover.Click { AppId = "not-a-generated-id" }, IntPtr.Zero, out started) && started == 0,
                "Missing button/window and unrelated IDs fail before native metadata queries and leave no process identity");
        }

        static bool Match(string buttonId, string buttonName, string path, string description, bool windowReadable,
            string windowId, bool processReadable, string processId, long started)
        {
            return TaskbarNativeSelection.MetadataMatches(buttonId, buttonName, path, SystemPath, description,
                windowReadable, windowId, processReadable, processId, started);
        }

        static void Metadata(Action<bool, string> check)
        {
            check(Match(Generated, "Task Manager", SystemPath, "Task Manager", true, "", true, "", 123),
                "Only an exact trusted-system target with readable absent explicit identities can become a weak candidate");
            check(Match(OtherGenerated, "Task Manager", SystemPath.ToLowerInvariant(), "Task Manager", true, "", true, "", 123),
                "Windows path casing is ignored while a second valid generated GUID remains only weak evidence");
            check(Match(Generated, "Gestionnaire des tâches", SystemPath, "Gestionnaire des tâches", true, "", true, "", 123) &&
                !Match(Generated, "Task Manager", SystemPath, "Gestionnaire des tâches", true, "", true, "", 123),
                "The button name follows the trusted OS file's localized description rather than a hardcoded English alias");
            foreach (string path in new[] { null, "", @"C:\Users\Test\Taskmgr.exe", @"C:\Windows\System32\Other.exe",
                @"C:\Windows\System32\Taskmgr.exe.fake", @"C:\Windows\SysWOW64\Taskmgr.exe", SystemPath + " ",
                @"C:\Windows\System32\Sub\..\Taskmgr.exe" })
                check(!Match(Generated, "Task Manager", path, "Task Manager", true, "", true, "", 123),
                    "A copied, basename-only, alternate-directory or malformed executable path cannot identify the trusted Task Manager");
            foreach (string name in new[] { null, "", "Taskmgr", "Other Task Manager", "Task Manager clone", "Task Manager - Chrome" })
                check(!Match(Generated, name, SystemPath, "Task Manager", true, "", true, "", 123),
                    "An unrelated or decorated button name cannot identify Task Manager");
            check(!Match(Generated, "Task Manager", SystemPath, "", true, "", true, "", 123) &&
                !Match(Generated, "Task Manager", SystemPath, "---", true, "", true, "", 123) &&
                !Match(Generated, "Task Manager", SystemPath, "Task Manager", true, "", true, "", 0) &&
                !Match(Generated, "Task Manager", SystemPath, "Task Manager", true, "", true, "", -1),
                "Unavailable trusted description or process creation metadata cannot authorize a weak candidate");
            foreach (string explicitIdentity in new[] { Generated, "Microsoft.Windows.TaskManager", "Another.App", " " }) {
                check(!Match(Generated, "Task Manager", SystemPath, "Task Manager", true, explicitIdentity, true, "", 123),
                    "Every nonempty HWND identity is authoritative and excludes the generated-name fallback");
                check(!Match(Generated, "Task Manager", SystemPath, "Task Manager", true, "", true, explicitIdentity, 123),
                    "Every nonempty process identity is authoritative and excludes the generated-name fallback");
            }
            check(!Match(Generated, "Task Manager", SystemPath, "Task Manager", false, "", true, "", 123) &&
                !Match(Generated, "Task Manager", SystemPath, "Task Manager", true, "", false, "", 123) &&
                !Match(Generated, "Task Manager", SystemPath, "Task Manager", true, null, true, "", 123) &&
                !Match(Generated, "Task Manager", SystemPath, "Task Manager", true, "", true, null, 123),
                "Failed or undecoded identity reads cannot be mistaken for genuine identity absence");
        }

        static void Readability(Action<bool, string> check)
        {
            string identity;
            check(WindowAppIdentity.TryDecode(0, 0, false, null, out identity) && identity == "",
                "A successful VT_EMPTY property proves an absent explicit HWND identity");
            check(WindowAppIdentity.TryDecode(0, 31, true, "", out identity) && identity == "" &&
                WindowAppIdentity.TryDecode(0, 31, true, "Explicit.App", out identity) && identity == "Explicit.App",
                "Readable empty strings and explicit HWND identities retain distinct successful results");
            foreach (int error in new[] { unchecked((int)0x80070005), unchecked((int)0x80004005), -1 })
                check(!WindowAppIdentity.TryDecode(error, 0, false, null, out identity) && identity == "" &&
                    !WindowAppIdentity.TryDecode(error, 31, true, "Explicit.App", out identity),
                    "Access-denied and COM query failures never prove that an explicit HWND identity is absent");
            check(!WindowAppIdentity.TryDecode(0, 31, false, "", out identity) &&
                !WindowAppIdentity.TryDecode(0, 31, true, null, out identity) &&
                !WindowAppIdentity.TryDecode(0, 1, false, null, out identity) &&
                !WindowAppIdentity.TryDecode(0, 3, false, null, out identity) &&
                !WindowAppIdentity.TryRead(IntPtr.Zero, out identity) && identity == "" && WindowAppIdentity.Read(IntPtr.Zero) == "",
                "Malformed/unsupported property variants and a missing window fail closed while legacy Read keeps its empty result");
            check(TaskbarNativeSelection.IsProcessIdentityAbsent(15703, 0) && TaskbarNativeSelection.IsProcessIdentityAbsent(0, 0) &&
                !TaskbarNativeSelection.IsProcessIdentityAbsent(5, 0) && !TaskbarNativeSelection.IsProcessIdentityAbsent(122, 0) &&
                !TaskbarNativeSelection.IsProcessIdentityAbsent(0, 10),
                "Only no-application or successful empty responses prove absent process AUMID; access/query failures do not");
            foreach (uint size in new uint[] { 1, 2, 128, 129 })
                check(TaskbarNativeSelection.CanReadProcessIdentity(122, size), "A bounded API buffer request can be read without treating it as identity absence");
            foreach (uint size in new uint[] { 0, 130, UInt32.MaxValue })
                check(!TaskbarNativeSelection.CanReadProcessIdentity(122, size), "Malformed or excessive process identity buffer lengths are rejected");
            check(!TaskbarNativeSelection.CanReadProcessIdentity(5, 129) && !TaskbarNativeSelection.CanReadProcessIdentity(0, 129),
                "A buffer length cannot hide an unrelated process identity API error");
        }

        static void Timing(Action<bool, string> check)
        {
            check(TaskbarNativeSelection.IsFreshEvent(100, 100, 100) && TaskbarNativeSelection.IsFreshEvent(100, 500, 1100),
                "Native activation evidence must fall within the bounded actual input gesture");
            check(!TaskbarNativeSelection.IsFreshEvent(100, 99, 500) && !TaskbarNativeSelection.IsFreshEvent(100, 501, 500) &&
                !TaskbarNativeSelection.IsFreshEvent(100, 500, 1101) && !TaskbarNativeSelection.IsFreshEvent(100, 500, 99),
                "Queued pre-click events, future timestamps, expired gestures and backward times cannot authorize weak selection");
            check(TaskbarNativeSelection.IsFreshEvent(UInt32.MaxValue - 100, 0, 200) &&
                !TaskbarNativeSelection.IsFreshEvent(UInt32.MaxValue - 100, UInt32.MaxValue - 101, 200) &&
                !TaskbarNativeSelection.IsFreshEvent(UInt32.MaxValue - 100, 0, 1000),
                "Native timestamp rollover retains valid short gestures and still rejects pre-click and expired evidence");
            check(!TaskbarNativeSelection.IsFreshGesture(100, unchecked(100U + 0x80000000U)) &&
                !TaskbarNativeSelection.IsFreshGesture(100, 99) && TaskbarNativeSelection.IsFreshGesture(100, 1100),
                "Signed wrap-safe gesture timing rejects ambiguous half-range and negative deltas with an inclusive one-second bound");
        }

        sealed class Fixture
        {
            internal readonly DateTime Now = new DateTime(2026, 10, 12, 20, 0, 0, DateTimeKind.Utc);
            internal const uint NowTick = 1300;
            internal TaskbarMover.Click Click;
            internal TaskbarTargets.Target Target;

            internal Fixture()
            {
                Target = new TaskbarTargets.Target {
                    Button = new TaskbarMover.Click { AppId = Generated, AppName = "Task Manager",
                        ButtonBounds = new Native.Rect { Left = 110, Top = 900, Right = 150, Bottom = 950 } },
                    Taskbar = new IntPtr(10), Window = new IntPtr(40), Process = 50, ProcessStarted = 60,
                    NeedsNativeSelection = true, Captured = Now.AddMilliseconds(-100),
                    TaskbarBounds = new Native.Rect { Left = 100, Top = 900, Right = 200, Bottom = 950 },
                    Windows = new[] { new TaskbarTargets.WindowIdentity {
                        Window = new IntPtr(40), Process = 50, ProcessStarted = 60, NeedsNativeSelection = true } }
                };
                Click = new TaskbarMover.Click {
                    AppId = Generated, AppName = "Task Manager", Position = new TaskbarMover.Point { X = 130, Y = 925 },
                    Taskbar = Target.Taskbar, PriorWindow = Target.Window, PriorProcess = Target.Process,
                    NativeGesture = true, NativeDownTime = 1000, Time = Now.AddMilliseconds(-300), ReleasedAt = Now.AddMilliseconds(-200),
                    Verification = new TaskbarTargets.Probe { Complete = true, Result = Target }
                };
            }

            internal bool Shape() { return TaskbarNativeSelection.HasGestureShape(Click, Target, Target.Window, NowTick, Now); }
            internal bool Minimize(bool minimized)
            { return TaskbarNativeSelection.HasMinimizeProof(Click, Target, Target.Window, minimized, NowTick, Now); }
            internal bool Activation(IntPtr selected, bool foreground, bool minimized, uint eventTime)
            { return TaskbarNativeSelection.HasActivationProof(Click, Target, selected, foreground, minimized, eventTime, NowTick, Now); }
        }

        static TaskbarTargets.Target Origin(TaskbarTargets.Target target)
        {
            return new TaskbarTargets.Target { Button = new TaskbarMover.Click { AppId = target.Button.AppId,
                    AppName = target.Button.AppName, Grouped = target.Button.Grouped, ButtonBounds = target.Button.ButtonBounds },
                Taskbar = target.Taskbar, Window = target.Window, Process = target.Process, ProcessStarted = target.ProcessStarted,
                NeedsNativeSelection = target.NeedsNativeSelection, Captured = target.Captured, TaskbarBounds = target.TaskbarBounds };
        }

        static void Reject(Action<bool, string> check, Action<Fixture> change, string reason)
        {
            var fixture = new Fixture(); change(fixture);
            check(!fixture.Shape(), "Weak native selection rejects " + reason);
        }

        static void NativeSelectionProof(Action<bool, string> check)
        {
            var fixture = new Fixture();
            check(fixture.Shape() && fixture.Minimize(true) && fixture.Activation(fixture.Target.Window, true, false, 1200),
                "A fresh released gesture and unique target admit actual native minimize or activation evidence");
            check(!fixture.Minimize(false), "A generated-ID button name alone cannot move a Task Manager that never minimized");
            check(!fixture.Activation(new IntPtr(90), true, false, 1200),
                "A copied Task Manager button activating a different HWND cannot move the real System Task Manager");
            check(!fixture.Activation(fixture.Target.Window, false, false, 1200) &&
                !fixture.Activation(fixture.Target.Window, true, true, 1200),
                "A matching window must actually be foreground and non-iconic for native activation proof");
            check(!fixture.Activation(fixture.Target.Window, true, false, 999) &&
                !fixture.Activation(fixture.Target.Window, true, false, 1301),
                "A pre-click queued event or future event cannot turn a copied button into native selection proof");
            fixture.Click.AppId = fixture.Target.Button.AppId = OtherGenerated;
            check(fixture.Shape() && !fixture.Minimize(false) && !fixture.Activation(new IntPtr(90), true, false, 1200),
                "A different valid generated GUID and copied trusted description remain weak: unrelated native actions never move the real target");
            fixture = new Fixture(); fixture.Click.PriorWindow = new IntPtr(90);
            check(!fixture.Minimize(true), "Minimize proof must identify the exact window that was foreground at mouse-down");
            fixture = new Fixture(); fixture.Click.PriorProcess++;
            check(!fixture.Minimize(true), "A recycled or changed prior PID cannot authorize native minimize recovery");
            fixture = new Fixture(); fixture.Click.PriorWasMinimized = true;
            check(!fixture.Minimize(true), "A window already minimized at mouse-down cannot supply a new minimize transition");
            fixture = new Fixture(); fixture.Click.Origin = Origin(fixture.Target);
            check(fixture.Shape(), "A separate unchanged hover origin can agree with the fresh weak selection snapshot");

            Reject(check, delegate(Fixture f) { f.Click.NativeGesture = false; }, "a fabricated non-input selection");
            Reject(check, delegate(Fixture f) { f.Target.NeedsNativeSelection = false; }, "a strong target entering the weak proof path");
            Reject(check, delegate(Fixture f) { f.Click.Grouped = true; }, "a grouped click");
            Reject(check, delegate(Fixture f) { f.Target.Button.Grouped = true; }, "a grouped fresh button");
            Reject(check, delegate(Fixture f) { f.Click.PreviewOnly = true; }, "a preview-only click");
            Reject(check, delegate(Fixture f) { f.Click.SelectionStarted = true; }, "a thumbnail selection");
            Reject(check, delegate(Fixture f) { f.Click.Time = DateTime.MinValue; }, "missing mouse-down time");
            Reject(check, delegate(Fixture f) { f.Click.Time = f.Now.AddTicks(1); }, "future mouse-down time");
            Reject(check, delegate(Fixture f) { f.Click.Time = f.Now.AddMilliseconds(-1001); }, "an expired click");
            Reject(check, delegate(Fixture f) { f.Click.ReleasedAt = DateTime.MinValue; }, "missing mouse release");
            Reject(check, delegate(Fixture f) { f.Click.ReleasedAt = f.Click.Time.AddTicks(-1); }, "release before mouse-down");
            Reject(check, delegate(Fixture f) { f.Click.ReleasedAt = f.Now.AddTicks(1); }, "future release");
            Reject(check, delegate(Fixture f) { f.Click.NativeDownTime = Fixture.NowTick - 1001; }, "an expired native gesture");
            Reject(check, delegate(Fixture f) { f.Click.NativeDownTime = Fixture.NowTick + 1; }, "a future native gesture");
            Reject(check, delegate(Fixture f) { f.Target.Button = null; }, "missing fresh button evidence");
            Reject(check, delegate(Fixture f) { f.Target.Button.AppId = "Other.App"; f.Click.AppId = "Other.App"; }, "an ordinary or explicit application ID");
            Reject(check, delegate(Fixture f) { f.Click.AppId = OtherGenerated; }, "a copied but different button identity");
            Reject(check, delegate(Fixture f) { f.Click.Verification = null; }, "missing fresh verification");
            Reject(check, delegate(Fixture f) { f.Click.Verification.Complete = false; }, "incomplete verification");
            Reject(check, delegate(Fixture f) { f.Click.Verification.Result = new TaskbarTargets.Target(); }, "a different verification result");
            Reject(check, delegate(Fixture f) { f.Click.Taskbar = new IntPtr(90); }, "a different clicked taskbar");
            Reject(check, delegate(Fixture f) { f.Target.Taskbar = f.Click.Taskbar = IntPtr.Zero; }, "a missing taskbar HWND");
            Reject(check, delegate(Fixture f) { f.Click.Position.X = 150; }, "a pointer outside the fresh button's right edge");
            Reject(check, delegate(Fixture f) { f.Click.Position.Y = 950; }, "a pointer outside the fresh button's bottom edge");
            Reject(check, delegate(Fixture f) { f.Target.Window = IntPtr.Zero; }, "a missing target HWND");
            Reject(check, delegate(Fixture f) { f.Target.Process = 0; }, "a missing target PID");
            Reject(check, delegate(Fixture f) { f.Target.ProcessStarted = 0; }, "a missing process creation identity");
            Reject(check, delegate(Fixture f) { f.Target.Windows = null; }, "missing window resolution");
            Reject(check, delegate(Fixture f) { f.Target.Windows = new TaskbarTargets.WindowIdentity[0]; }, "no resolved window");
            Reject(check, delegate(Fixture f) { f.Target.Windows = new[] { f.Target.Windows[0], f.Target.Windows[0] }; }, "ambiguous or duplicate windows");
            Reject(check, delegate(Fixture f) { f.Target.Windows[0] = null; }, "an unavailable unique identity");
            Reject(check, delegate(Fixture f) { f.Target.Windows[0].Window = new IntPtr(90); }, "a different resolved HWND");
            Reject(check, delegate(Fixture f) { f.Target.Windows[0].Process++; }, "a different resolved PID");
            Reject(check, delegate(Fixture f) { f.Target.Windows[0].ProcessStarted++; }, "a changed process creation identity");
            Reject(check, delegate(Fixture f) { f.Target.Windows[0].NeedsNativeSelection = false; }, "inconsistent identity strength");
            Reject(check, delegate(Fixture f) { f.Target.Captured = f.Click.Time.AddTicks(-1); }, "a pre-click target snapshot");
            Reject(check, delegate(Fixture f) { f.Target.Captured = f.Now.AddTicks(1); }, "a future target snapshot");
            Reject(check, delegate(Fixture f) { f.Click.Origin = Origin(f.Target); f.Click.Origin.Button.AppId = OtherGenerated; }, "a changed hover button ID");
            Reject(check, delegate(Fixture f) { f.Click.Origin = Origin(f.Target); f.Click.Origin.Window = new IntPtr(90); }, "a changed hover target");
            Reject(check, delegate(Fixture f) { f.Click.Origin = Origin(f.Target); f.Click.Origin.NeedsNativeSelection = false; }, "a changed hover identity strength");
            Reject(check, delegate(Fixture f) { f.Click.Origin = Origin(f.Target); f.Click.Origin.ProcessStarted++; }, "a changed hover process lifetime");
            Reject(check, delegate(Fixture f) { f.Click.Origin = Origin(f.Target); f.Click.Origin.Button.ButtonBounds.Right++; }, "a changed hover button rectangle");
            Reject(check, delegate(Fixture f) { f.Click.Origin = Origin(f.Target); f.Click.Origin.TaskbarBounds.Bottom++; }, "a changed hover taskbar rectangle");

            check(!TaskbarNativeSelection.HasGestureShape(null, fixture.Target, fixture.Target.Window, Fixture.NowTick, fixture.Now) &&
                !TaskbarNativeSelection.HasGestureShape(fixture.Click, null, fixture.Target.Window, Fixture.NowTick, fixture.Now) &&
                !TaskbarNativeSelection.HasGestureShape(fixture.Click, fixture.Target, new IntPtr(90), Fixture.NowTick, fixture.Now),
                "A missing click/target or mismatched selected HWND cannot authorize native selection");
        }
    }
