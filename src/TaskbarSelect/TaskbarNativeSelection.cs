using System;
using System.Diagnostics;
using System.IO;
using System.Runtime.InteropServices;
using System.Text;
using Microsoft.Win32.SafeHandles;

namespace TaskbarSelect
{
    // A default Explorer ID cannot prove which executable owns its button.
    // This identifies only a possible Task Manager target. Callers must observe
    // Windows selecting that exact window before movement; never intercept its
    // button or use this as ordinary application identity.
    internal static class TaskbarNativeSelection
    {
        const string GeneratedPrefix = "Microsoft.AutoGenerated.";
        const uint QueryLimitedInformation = 0x1000;
        const int NoApplication = 15703, InsufficientBuffer = 122, MaximumIdentityCharacters = 129;
        internal const int GestureMilliseconds = 1000;
        internal static bool IsPhysicalPointer(uint flags) { return (flags & 3) == 0; }

        sealed class KernelHandle : SafeHandleZeroOrMinusOneIsInvalid
        {
            public KernelHandle() : base(true) { }
            protected override bool ReleaseHandle() { return CloseHandle(handle); }
        }
        [DllImport("kernel32.dll", SetLastError = true)] static extern KernelHandle OpenProcess(uint access, bool inherit, uint process);
        [DllImport("kernel32.dll")] static extern bool CloseHandle(IntPtr handle);
        [DllImport("kernel32.dll", CharSet = CharSet.Unicode)]
        static extern int GetApplicationUserModelId(KernelHandle process, ref uint length, StringBuilder identity);

        sealed class TrustedTaskManager
        {
            internal string Path, Description;
        }
        static readonly Lazy<TrustedTaskManager> trusted = new Lazy<TrustedTaskManager>(ReadTrustedTaskManager);
        static TrustedTaskManager ReadTrustedTaskManager()
        {
            try {
                string system = Environment.GetFolderPath(Environment.SpecialFolder.System);
                if (String.IsNullOrEmpty(system)) return null;
                string path = Path.Combine(system, "Taskmgr.exe");
                string description = FileVersionInfo.GetVersionInfo(path).FileDescription;
                if (String.IsNullOrEmpty(NormalizeName(description))) return null;
                return new TrustedTaskManager { Path = path, Description = description };
            }
            catch (IOException) { return null; }
            catch (UnauthorizedAccessException) { return null; }
            catch (ArgumentException) { return null; }
            catch (NotSupportedException) { return null; }
            catch (System.ComponentModel.Win32Exception) { return null; }
            catch (System.Security.SecurityException) { return null; }
        }

        internal static bool IsGeneratedIdentity(string identity)
        {
            if (identity == null || identity.Length != GeneratedPrefix.Length + 38 ||
                !identity.StartsWith(GeneratedPrefix, StringComparison.Ordinal)) return false;
            Guid value;
            return Guid.TryParseExact(identity.Substring(GeneratedPrefix.Length), "B", out value);
        }

        internal static string NormalizeName(string value)
        {
            if (String.IsNullOrEmpty(value)) return "";
            var normalized = new StringBuilder(value.Length);
            foreach (char item in value) if (Char.IsLetterOrDigit(item)) normalized.Append(Char.ToLowerInvariant(item));
            return normalized.ToString();
        }

        internal static bool MetadataMatches(string buttonIdentity, string buttonName, string processPath, string trustedPath,
            string trustedDescription, bool windowReadable, string windowIdentity, bool processReadable, string processIdentity,
            long processStarted)
        {
            string description = NormalizeName(trustedDescription);
            return IsGeneratedIdentity(buttonIdentity) && processStarted > 0 &&
                !String.IsNullOrEmpty(trustedPath) && String.Equals(processPath, trustedPath, StringComparison.OrdinalIgnoreCase) &&
                description.Length != 0 && String.Equals(NormalizeName(buttonName), description, StringComparison.Ordinal) &&
                windowReadable && windowIdentity != null && windowIdentity.Length == 0 &&
                processReadable && processIdentity != null && processIdentity.Length == 0;
        }

        internal static bool TryIdentifyTaskManager(TaskbarMover.Click button, IntPtr window, out long processStarted)
        {
            processStarted = 0;
            if (button == null || button.Grouped || window == IntPtr.Zero || !IsGeneratedIdentity(button.AppId)) return false;
            TrustedTaskManager expected = trusted.Value;
            if (expected == null || NormalizeName(button.AppName) != NormalizeName(expected.Description)) return false;
            uint process;
            if (Native.GetWindowThreadProcessId(window, out process) == 0 || process == 0) return false;
            long started = NativeProcessIdentity.Started(process);
            string path = NativeProcessIdentity.Path(process);
            if (started <= 0 || !String.Equals(path, expected.Path, StringComparison.OrdinalIgnoreCase)) return false;
            string windowIdentity, processIdentity;
            bool windowReadable = WindowAppIdentity.TryRead(window, out windowIdentity);
            if (!windowReadable || !String.IsNullOrEmpty(windowIdentity)) return false;
            bool processReadable = TryReadProcessIdentity(process, out processIdentity);
            if (!MetadataMatches(button.AppId, button.AppName, path, expected.Path, expected.Description,
                windowReadable, windowIdentity, processReadable, processIdentity, started)) return false;
            uint currentProcess;
            if (Native.GetWindowThreadProcessId(window, out currentProcess) == 0 || currentProcess != process ||
                NativeProcessIdentity.Started(process) != started) return false;
            processStarted = started;
            return true;
        }

        static bool TryReadProcessIdentity(uint process, out string identity)
        {
            identity = "";
            if (process == 0) return false;
            using (var handle = OpenProcess(QueryLimitedInformation, false, process)) {
                if (handle == null || handle.IsInvalid) return false;
                uint length = 0;
                int result = GetApplicationUserModelId(handle, ref length, null);
                if (IsProcessIdentityAbsent(result, length)) return true;
                if (!CanReadProcessIdentity(result, length)) return false;
                var value = new StringBuilder((int)length);
                result = GetApplicationUserModelId(handle, ref length, value);
                if (result != 0 || length == 0 || length > MaximumIdentityCharacters || value.Length >= length) return false;
                identity = value.ToString();
                return true;
            }
        }

        internal static bool IsProcessIdentityAbsent(int result, uint length)
        { return result == NoApplication || (result == 0 && length == 0); }

        internal static bool CanReadProcessIdentity(int result, uint length)
        { return result == InsufficientBuffer && length > 0 && length <= MaximumIdentityCharacters; }

        internal static bool IsFreshGesture(uint down, uint now)
        {
            int elapsed = unchecked((int)(now - down));
            return elapsed >= 0 && elapsed <= GestureMilliseconds;
        }

        internal static bool IsFreshEvent(uint down, uint eventTime, uint now)
        {
            int sinceDown = unchecked((int)(eventTime - down)), sinceEvent = unchecked((int)(now - eventTime));
            return IsFreshGesture(down, now) && sinceDown >= 0 && sinceDown <= GestureMilliseconds &&
                sinceEvent >= 0 && sinceEvent <= GestureMilliseconds;
        }

        internal static bool ObserveForegroundForClick(TaskbarMover.Click candidate, uint eventTime, uint now)
        {
            // Out-of-context WinEvents can be delivered after a later mouse-down.
            // Such an older event must not replace that click's selection evidence.
            return candidate == null || !candidate.NativeGesture || candidate.PreviewOnly ||
                candidate.Taskbar == IntPtr.Zero || candidate.Verification == null || !candidate.Verification.Complete ||
                candidate.Verification.Result == null || !candidate.Verification.Result.NeedsNativeSelection ||
                IsFreshEvent(candidate.NativeDownTime, eventTime, now);
        }

        internal static bool CanAwaitSelection(TaskbarMover.Click candidate, TaskbarTargets.Target target,
            uint nowTick, DateTime nowUtc)
        {
            return candidate != null && NativeTaskbarHandoff.WithinDeadline(candidate.NativeDownTime, nowTick) &&
                HasGestureShape(candidate, target, target == null ? IntPtr.Zero : target.Window, nowTick, nowUtc);
        }

        internal static bool DirectGestureAllowed(bool needsNativeSelection, bool physicalDown, bool physicalUp,
            uint downTime, uint upTime, uint nowTime, bool modified)
        {
            return !needsNativeSelection || (physicalDown && physicalUp && !modified &&
                NativeTaskbarHandoff.WithinDeadline(downTime, nowTime) && IsFreshEvent(downTime, upTime, nowTime));
        }

        internal static bool DirectTargetShape(TaskbarTargets.Target target)
        {
            if (target == null || target.Button == null) return false;
            if (!target.NeedsNativeSelection) return true;
            return target.Window != IntPtr.Zero && target.Process != 0 && target.ProcessStarted > 0 &&
                target.Taskbar != IntPtr.Zero && target.Button.Taskbar == target.Taskbar &&
                !target.Button.Grouped && !target.Button.PreviewOnly && !target.Button.SelectionStarted &&
                (target.ShellOnly ? TaskManagerShellIdentity.ManagementConsoleIdentityAllowed(target.Button.AppId) : IsGeneratedIdentity(target.Button.AppId)) &&
                target.ShellProof != null && target.ShellProof.ShellOnly == target.ShellOnly &&
                target.Windows != null && target.Windows.Length == 1 &&
                target.Windows[0] != null && target.Windows[0].Window == target.Window && target.Windows[0].Process == target.Process &&
                target.Windows[0].ProcessStarted == target.ProcessStarted && target.Windows[0].NeedsNativeSelection &&
                target.Windows[0].ShellOnly == target.ShellOnly &&
                TaskManagerShellIdentity.ProofsMatch(target.ShellProof, target.Windows[0].ShellProof) &&
                TaskManagerShellIdentity.ProofMatchesTarget(target.ShellProof, target.Window, target.Process,
                    target.ProcessStarted, target.Taskbar, target.Button.AppId);
        }

        internal static bool HasGestureShape(TaskbarMover.Click candidate, TaskbarTargets.Target target,
            IntPtr selected, uint nowTick, DateTime nowUtc)
        {
            if (candidate == null || target == null || !candidate.NativeGesture || !target.NeedsNativeSelection ||
                candidate.PreviewOnly || candidate.SelectionStarted || candidate.Grouped ||
                candidate.Time == DateTime.MinValue || candidate.Time > nowUtc || nowUtc - candidate.Time > TimeSpan.FromMilliseconds(GestureMilliseconds) ||
                candidate.ReleasedAt == DateTime.MinValue || candidate.ReleasedAt < candidate.Time || candidate.ReleasedAt > nowUtc ||
                nowUtc - candidate.ReleasedAt > TimeSpan.FromMilliseconds(GestureMilliseconds) ||
                !IsFreshGesture(candidate.NativeDownTime, nowTick) ||
                target.Button == null || target.Button.Grouped ||
                !(target.ShellOnly ? DirectTargetShape(target) : IsGeneratedIdentity(target.Button.AppId)) ||
                !String.Equals(candidate.AppId, target.Button.AppId, StringComparison.OrdinalIgnoreCase) ||
                candidate.Verification == null || !candidate.Verification.Complete || candidate.Verification.Result != target ||
                target.Taskbar == IntPtr.Zero || candidate.Taskbar != target.Taskbar ||
                !TaskbarMover.Contains(target.Button.ButtonBounds, candidate.Position) ||
                selected == IntPtr.Zero || selected != target.Window || target.Process == 0 || target.ProcessStarted <= 0 ||
                target.Windows == null || target.Windows.Length != 1 || target.Windows[0] == null ||
                target.Windows[0].Window != selected || target.Windows[0].Process != target.Process ||
                !target.Windows[0].NeedsNativeSelection || target.Windows[0].ProcessStarted != target.ProcessStarted ||
                target.Windows[0].ShellOnly != target.ShellOnly ||
                target.Captured < candidate.Time || target.Captured > nowUtc ||
                (candidate.Origin != null && !TaskbarTargets.SameButton(candidate.Origin, target))) return false;
            return true;
        }
        internal static bool HasBoundShellSelectionProof(TaskbarMover.Click candidate, TaskbarTargets.Target target,
            IntPtr window, uint nowTick, DateTime nowUtc)
        {
            return target != null && target.ShellOnly && HasGestureShape(candidate, target, window, nowTick, nowUtc) &&
                TaskManagerShellIdentity.ProofIsCurrent(target.ShellProof) &&
                TaskManagerShellIdentity.ProofMatchesTarget(target.ShellProof, window, target.Process,
                    target.ProcessStarted, target.Taskbar, target.Button.AppId);
        }

        internal static bool HasMinimizeProof(TaskbarMover.Click candidate, TaskbarTargets.Target target,
            IntPtr selected, bool currentlyMinimized, uint nowTick, DateTime nowUtc)
        {
            return HasGestureShape(candidate, target, selected, nowTick, nowUtc) && currentlyMinimized &&
                !candidate.PriorWasMinimized && candidate.PriorWindow == selected && candidate.PriorProcess == target.Process;
        }

        internal static bool HasActivationProof(TaskbarMover.Click candidate, TaskbarTargets.Target target,
            IntPtr selected, bool currentlyForeground, bool currentlyMinimized, uint eventTime, uint nowTick, DateTime nowUtc)
        {
            return HasGestureShape(candidate, target, selected, nowTick, nowUtc) && currentlyForeground && !currentlyMinimized &&
                IsFreshEvent(candidate.NativeDownTime, eventTime, nowTick);
        }
    }
}
