using System;
using System.Collections;
using System.Collections.Generic;
using System.Runtime.InteropServices;
using System.Windows;
using System.Windows.Automation;

namespace TaskbarSelect
{
    // Pure cached-provider fixtures only. No shell/UIA query, HWND, hook,
    // foreground request, application profile or real input is created here.
    internal static class TaskbarButtonSelectionTests
    {
        sealed class SnapshotProvider : IEnumerable<TaskbarButtonSnapshot>
        {
            internal readonly TaskbarButtonSnapshot[] Entries;
            internal int Enumerations, Moves, CachedReads, Disposals;
            internal int FaultIndex = -1;
            internal bool FaultOnEnumeration, FaultOnCurrent, FaultOnDispose;
            internal Exception Failure = new InvalidOperationException("Owned cached provider is unavailable.");

            internal SnapshotProvider(params TaskbarButtonSnapshot[] entries) { Entries = entries; }
            public IEnumerator<TaskbarButtonSnapshot> GetEnumerator()
            {
                Enumerations++;
                if (FaultOnEnumeration) throw Failure;
                return new SnapshotEnumerator(this);
            }
            IEnumerator IEnumerable.GetEnumerator() { return GetEnumerator(); }

            sealed class SnapshotEnumerator : IEnumerator<TaskbarButtonSnapshot>
            {
                readonly SnapshotProvider owner;
                int index = -1;
                bool disposed;
                internal SnapshotEnumerator(SnapshotProvider owner) { this.owner = owner; }
                public bool MoveNext()
                {
                    if (disposed) throw new InvalidOperationException("Owned enumeration was already disposed.");
                    owner.Moves++; index++;
                    if (!owner.FaultOnCurrent && index == owner.FaultIndex) throw owner.Failure;
                    return index < owner.Entries.Length;
                }
                public TaskbarButtonSnapshot Current
                {
                    get {
                        if (disposed || index < 0 || index >= owner.Entries.Length) throw new InvalidOperationException("Owned cached cursor is invalid.");
                        if (owner.FaultOnCurrent && index == owner.FaultIndex) throw owner.Failure;
                        owner.CachedReads++;
                        return owner.Entries[index];
                    }
                }
                object IEnumerator.Current { get { return Current; } }
                public void Reset() { throw new NotSupportedException(); }
                public void Dispose() { if (!disposed) { disposed = true; owner.Disposals++; if (owner.FaultOnDispose) throw owner.Failure; } }
            }
        }

        static readonly Rect HitBounds = new Rect(40, 900, 48, 48);
        static readonly TaskbarMover.Point HitPoint = new TaskbarMover.Point { X = 60, Y = 920 };
        static TaskbarButtonSnapshot Snapshot(string id, string name = "Task Manager", Rect? bounds = null)
        { return new TaskbarButtonSnapshot { AutomationId = id, Name = name, Bounds = bounds ?? HitBounds }; }
        static TaskbarMover.Click Previous()
        {
            return new TaskbarMover.Click { AppId = "previous-id", AppName = "previous-name", Grouped = true,
                ButtonBounds = new Native.Rect { Left = 1, Top = 2, Right = 3, Bottom = 4 },
                Position = new TaskbarMover.Point { X = 7, Y = 8 } };
        }
        static bool Unchanged(TaskbarMover.Click candidate)
        {
            return candidate.AppId == "previous-id" && candidate.AppName == "previous-name" && candidate.Grouped &&
                candidate.ButtonBounds.Left == 1 && candidate.ButtonBounds.Top == 2 && candidate.ButtonBounds.Right == 3 && candidate.ButtonBounds.Bottom == 4 &&
                candidate.Position.X == 7 && candidate.Position.Y == 8;
        }
        static bool BoundsEqual(Native.Rect bounds, int left, int top, int right, int bottom)
        { return bounds.Left == left && bounds.Top == top && bounds.Right == right && bounds.Bottom == bottom; }

        static void OrderedCachedProvider(Action<bool, string> check)
        {
            var entries = new TaskbarButtonSnapshot[4096];
            for (int index = 0; index < entries.Length; index++)
                entries[index] = index % 4 == 0 ? Snapshot("Appid: Unrelated." + index, null, new Rect(100 + index, 900, 30, 40)) :
                    Snapshot("Other.UIA.Child." + index, null);
            entries[3111] = Snapshot("aPpId: Microsoft.AutoGenerated.UnitFixture", "Task Manager - 1 running window");
            var provider = new SnapshotProvider(entries);
            var candidate = Previous();
            check(TaskbarButtonReader.SelectAppButton(provider, HitPoint, candidate), "A large ordered cached tree resolves its late taskbar hit without a shell query");
            check(candidate.AppId == "Microsoft.AutoGenerated.UnitFixture" && candidate.AppName == "Task Manager" && !candidate.Grouped,
                "Cached taskbar selection preserves ID casing and parses the running-window name");
            check(BoundsEqual(candidate.ButtonBounds, 40, 900, 88, 948) && candidate.Position.X == 7 && candidate.Position.Y == 8,
                "The cached hit commits native button bounds without changing click position");
            check(provider.Enumerations == 1 && provider.CachedReads == entries.Length && provider.Moves == entries.Length + 1 && provider.Disposals == 1,
                "Selection consumes one complete cached enumeration and disposes it after checking late ambiguity");

            // A copied snapshot stays usable after the original source values
            // change. The selection boundary has no live provider callback.
            var original = Snapshot("Appid: Captured.App", "Captured app");
            var captured = Snapshot(original.AutomationId, original.Name, original.Bounds);
            original.AutomationId = "Appid: Replaced.App"; original.Name = "Replaced app"; original.Bounds = Rect.Empty;
            candidate = Previous();
            check(TaskbarButtonReader.SelectAppButton(new[] { captured }, HitPoint, candidate) && candidate.AppId == "Captured.App" && candidate.AppName == "Captured app",
                "Pure selection uses the captured values without rereading a changed live source");
        }

        static void IdentityAndBounds(Action<bool, string> check)
        {
            foreach (string prefix in new[] { "Appid: ", "APPID: ", "aPpId: " }) {
                var candidate = Previous();
                check(TaskbarButtonReader.SelectAppButton(new[] { Snapshot(prefix + "Mixed.Case.Id") }, HitPoint, candidate) && candidate.AppId == "Mixed.Case.Id",
                    "Appid prefix matching is case insensitive and leaves the ID value intact: " + prefix);
            }
            foreach (string id in new[] { null, "", "Other: Test", "Appid:", "Appid: " }) {
                var candidate = Previous();
                check(!TaskbarButtonReader.SelectAppButton(new[] { Snapshot(id) }, HitPoint, candidate) && Unchanged(candidate),
                    "A missing, unrelated or empty taskbar identity cannot overwrite the prior click");
            }
            var named = Previous();
            check(TaskbarButtonReader.SelectAppButton(new[] { Snapshot("Unrelated", null), Snapshot("Appid: Grouped.App", "Example - 2 running windows") }, HitPoint, named) &&
                named.AppName == "Example" && named.Grouped, "Known unrelated cached nodes may omit names while a real grouped button retains grouping");

            foreach (TaskbarMover.Point point in new[] {
                new TaskbarMover.Point { X = 40, Y = 900 }, new TaskbarMover.Point { X = 88, Y = 948 },
                new TaskbarMover.Point { X = 88, Y = 920 }, new TaskbarMover.Point { X = 60, Y = 948 } }) {
                var candidate = Previous();
                check(TaskbarButtonReader.SelectAppButton(new[] { Snapshot("Appid: Boundary.App") }, point, candidate),
                    "Cached hit testing preserves the original WPF inclusive rectangle edges at " + point.X + "," + point.Y);
            }
            foreach (TaskbarMover.Point point in new[] {
                new TaskbarMover.Point { X = 39, Y = 920 }, new TaskbarMover.Point { X = 89, Y = 920 },
                new TaskbarMover.Point { X = 60, Y = 899 }, new TaskbarMover.Point { X = 60, Y = 949 } }) {
                var candidate = Previous();
                check(!TaskbarButtonReader.SelectAppButton(new[] { Snapshot("Appid: Outside.App") }, point, candidate) && Unchanged(candidate),
                    "Outside cached button bounds fail closed at " + point.X + "," + point.Y);
            }
            var empty = Previous();
            check(!TaskbarButtonReader.SelectAppButton(new[] { Snapshot("Appid: Empty.Geometry", bounds: Rect.Empty) }, HitPoint, empty) && Unchanged(empty),
                "An empty cached rectangle cannot authorize a button hit");
            foreach (Rect invalid in new[] { new Rect(60, 920, 0, 0), new Rect(Double.NaN, 900, 48, 48),
                new Rect(Double.PositiveInfinity, 900, 48, 48), new Rect((double)Int32.MaxValue + 1, 900, 48, 48),
                new Rect((double)Int32.MinValue - 1, 900, 48, 48) }) {
                var candidate = Previous();
                check(!TaskbarButtonReader.SelectAppButton(new[] { Snapshot("Appid: Invalid.Geometry", bounds: invalid) }, HitPoint, candidate) && Unchanged(candidate),
                    "Degenerate, non-finite or out-of-native-range cached geometry fails without committing unusable bounds");
            }
        }

        static void AmbiguityAndAtomicCommit(Action<bool, string> check)
        {
            var duplicates = Previous();
            check(TaskbarButtonReader.SelectAppButton(new[] { Snapshot("Appid: Exact.App"), Snapshot("APPID: EXACT.APP") }, HitPoint, duplicates) && duplicates.AppId == "Exact.App",
                "Duplicate records are accepted only when their case-folded identity, exact name and rectangle agree");
            foreach (TaskbarButtonSnapshot other in new[] {
                Snapshot("Appid: Other.App"), Snapshot("Appid: Exact.App", "Other name"),
                Snapshot("Appid: Exact.App", "task manager"), Snapshot("Appid: Exact.App", bounds: new Rect(40, 900, 49, 48)) }) {
                var candidate = Previous(); var provider = new SnapshotProvider(Snapshot("Appid: Exact.App"), other);
                check(!TaskbarButtonReader.SelectAppButton(provider, HitPoint, candidate) && Unchanged(candidate),
                    "Two hit records with different identity, exact name or exact bounds remain ambiguous without a partial commit");
                check(provider.Disposals == 1, "Ambiguous cached selection disposes its owned provider cursor");
            }
            var late = new TaskbarButtonSnapshot[512];
            for (int index = 0; index < late.Length; index++) late[index] = Snapshot("Unrelated." + index, null);
            late[0] = Snapshot("Appid: First.App"); late[late.Length - 1] = Snapshot("Appid: Last.App");
            var final = Previous();
            check(!TaskbarButtonReader.SelectAppButton(new SnapshotProvider(late), HitPoint, final) && Unchanged(final),
                "A conflicting hit at the end of a large cached tree prevents an earlier provisional match from committing");
            foreach (TaskbarButtonSnapshot[] records in new[] { new TaskbarButtonSnapshot[0], new TaskbarButtonSnapshot[] { null },
                new[] { Snapshot("Appid: First.App"), null }, new[] { null, Snapshot("Appid: First.App") } }) {
                var candidate = Previous();
                check(!TaskbarButtonReader.SelectAppButton(records, HitPoint, candidate) && Unchanged(candidate),
                    "Empty or malformed snapshot sequences fail closed without changing the prior candidate");
            }
            var missing = Previous();
            check(!TaskbarButtonReader.SelectAppButton(null, HitPoint, missing) && Unchanged(missing), "A missing cached provider leaves the prior click unchanged");
            check(!TaskbarButtonReader.SelectAppButton(new[] { Snapshot("Appid: Test.App") }, HitPoint, null), "A missing candidate is refused without touching a provider or the desktop");
        }

        static void ProviderFailures(Action<bool, string> check)
        {
            foreach (Exception failure in new Exception[] {
                new InvalidOperationException("Owned stale cached provider"), new ElementNotAvailableException("Owned vanished cached provider"),
                new COMException("Owned cached provider failure", unchecked((int)0x80040201)) })
                foreach (bool current in new[] { false, true }) {
                    var provider = new SnapshotProvider(Snapshot("Appid: Provisional.App"), Snapshot("Unrelated", null)) {
                        FaultIndex = 1, FaultOnCurrent = current, Failure = failure
                    };
                    var candidate = Previous();
                    check(!TaskbarButtonReader.SelectAppButton(provider, HitPoint, candidate) && Unchanged(candidate),
                        "A stale unrelated node after a provisional hit fails the entire cached selection closed: " + failure.GetType().Name + "/" + (current ? "Current" : "MoveNext"));
                    check(provider.Disposals == 1, "A failing cached provider cursor is disposed without live UIA retries");
                }
            var enumeration = new SnapshotProvider(Snapshot("Appid: Test.App")) { FaultOnEnumeration = true };
            var previous = Previous();
            check(!TaskbarButtonReader.SelectAppButton(enumeration, HitPoint, previous) && Unchanged(previous) && enumeration.Enumerations == 1 && enumeration.Disposals == 0,
                "Failure to create a cached enumeration leaves the prior candidate unchanged and creates no live provider retry");
            var disposal = new SnapshotProvider(Snapshot("Appid: Provisional.App")) { FaultOnDispose = true };
            previous = Previous();
            check(!TaskbarButtonReader.SelectAppButton(disposal, HitPoint, previous) && Unchanged(previous) && disposal.Disposals == 1,
                "A cached provider disposal failure prevents provisional values from committing after enumeration");
        }

        internal static void Run(Action<bool, string> check)
        {
            OrderedCachedProvider(check);
            IdentityAndBounds(check);
            AmbiguityAndAtomicCommit(check);
            ProviderFailures(check);
        }
    }
}
