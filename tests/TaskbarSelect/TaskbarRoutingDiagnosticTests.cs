using System;

namespace TaskbarSelect
{
    // Pure diagnostic receipts only. No HWND/process lookup, hook, input,
    // permission request, profile, foreground or movement operation is used.
    internal static class TaskbarRoutingDiagnosticTests
    {
        const string PrivateMarker = "PrivateApplicationIdentifier";
        internal static void Run(Action<bool, string> check)
        {
            FrozenProbe(check);
            GestureReceipt(check);
            HookReceipt(check);
            ButtonClassification(check);
        }

        static void ButtonClassification(Action<bool, string> check)
        {
            check(TaskbarTargets.ClassifyButtonIdentity(null) == TaskbarTargets.ButtonIdentityKind.None &&
                TaskbarTargets.ClassifyButtonIdentity("") == TaskbarTargets.ButtonIdentityKind.None &&
                TaskbarTargets.ClassifyButtonIdentity("Microsoft.AutoGenerated.{11111111-2222-4333-8444-555555555555}") == TaskbarTargets.ButtonIdentityKind.Generated &&
                TaskbarTargets.ClassifyButtonIdentity("PrivateApplicationIdentifier") == TaskbarTargets.ButtonIdentityKind.Other,
                "Button diagnostics distinguish missing, generated and opaque identifiers without printing them");
            var state = new TaskbarTargets.DiagnosticState();
            state.Button(new TaskbarMover.Click { AppId = PrivateMarker, Grouped = true });
            state.Close(TaskbarTargets.DiagnosticOutcome.Matched);
            state.Button(new TaskbarMover.Click());
            string text = TaskbarTargets.ShellProofDescription(state.Snapshot());
            check(text.Contains("button=Other grouped=1") && !text.Contains(PrivateMarker),
                "Closed button classification and grouping survive late writes while keeping the identifier private");
        }

        static TaskbarTargets.Diagnostic Evidence()
        {
            return new TaskbarTargets.Diagnostic {
                Stage = TaskbarTargets.DiagnosticStage.ResolveWindows, Outcome = TaskbarTargets.DiagnosticOutcome.Matched,
                TaskManagerAppId = PrivateMarker, ShellProof = TaskbarTargets.ShellProofOutcome.Proved,
                ShellPhase = TaskbarTargets.ShellProofPhase.Complete, ShellBudgetMilliseconds = 350,
                ShellMilliseconds = 40, ElapsedMilliseconds = 50, CandidateWindows = 1
            };
        }

        static void FrozenProbe(Action<bool, string> check)
        {
            var state = new TaskbarTargets.DiagnosticState();
            state.Begin(); state.ShellBegin(Int32.MaxValue);
            check(state.Snapshot().ShellBudgetMilliseconds == 9999,
                "Probe shell-budget diagnostics remain bounded even for malformed provider values");
            var copy = state.Snapshot(); copy.ShellProof = TaskbarTargets.ShellProofOutcome.ReadError;
            copy.ShellBudgetMilliseconds = -1;
            check(state.Snapshot().ShellProof == TaskbarTargets.ShellProofOutcome.Pending &&
                state.Snapshot().ShellBudgetMilliseconds == 9999,
                "A diagnostic consumer cannot mutate the reader's live state through its snapshot");
            state.ShellPhase(TaskbarTargets.ShellProofPhase.Reader);
            state.ShellEnd(TaskbarTargets.ShellProofOutcome.Proved);
            state.Button(new TaskbarMover.Click { AppName = "Task Manager", AppId = PrivateMarker });
            state.Close(TaskbarTargets.DiagnosticOutcome.Matched);
            string frozen = TaskbarTargets.ShellProofDescription(state.Snapshot());
            state.ShellBegin(1); state.ShellPhase(TaskbarTargets.ShellProofPhase.Identity);
            state.ShellEnd(TaskbarTargets.ShellProofOutcome.IdentityMismatch);
            state.Error(-1); state.Stage(TaskbarTargets.DiagnosticStage.Preview);
            state.Button(new TaskbarMover.Click { AppName = "Task Manager", AppId = "ChangedIdentifier" });
            state.Close(TaskbarTargets.DiagnosticOutcome.ReaderTimeout);
            var after = state.Snapshot();
            check(TaskbarTargets.ShellProofDescription(after) == frozen && after.Outcome == TaskbarTargets.DiagnosticOutcome.Matched &&
                after.Stage == TaskbarTargets.DiagnosticStage.Reader && after.TaskManagerAppId == PrivateMarker,
                "Retired or late provider writes cannot replace a closed probe's outcome, timing or identifier snapshot");
            var timedOut = new TaskbarTargets.DiagnosticState(); timedOut.ShellBegin(350);
            timedOut.Close(TaskbarTargets.DiagnosticOutcome.ReaderTimeout);
            check(timedOut.Snapshot().ShellProof == TaskbarTargets.ShellProofOutcome.ProbeExpired,
                "A pending shell proof records probe expiry when its owner times out");
            var malformed = Evidence(); malformed.ShellProof = (TaskbarTargets.ShellProofOutcome)Int32.MaxValue;
            malformed.ShellPhase = (TaskbarTargets.ShellProofPhase)(-1);
            malformed.ShellBudgetMilliseconds = Int32.MaxValue; malformed.ShellMilliseconds = Int32.MinValue;
            string text = TaskbarTargets.ShellProofDescription(malformed);
            check(text.Contains("shell=Unknown/Unknown") && text.Contains("b=9999 t=0") && !text.Contains(PrivateMarker) && text.Length < 200,
                "Safe shell formatting uses bounded numbers and known enums without arbitrary application content");
            malformed.ShellProof = TaskbarTargets.ShellProofOutcome.BudgetSkipped;
            string skipped = TaskbarTargets.ShellProofDescription(malformed);
            malformed.ShellProof = TaskbarTargets.ShellProofOutcome.ReaderBusy;
            check(skipped != TaskbarTargets.ShellProofDescription(malformed) && skipped.Contains("BudgetSkipped") &&
                TaskbarTargets.ShellProofDescription(malformed).Contains("ReaderBusy"),
                "Budget exhaustion and a busy resolver remain distinct observable causes without changing movement authority");
        }

        static void GestureReceipt(Action<bool, string> check)
        {
            var receipt = new TaskbarGestureDiagnostics();
            receipt.Direct(TaskbarDirectDecision.Accepted); receipt.Stopped();
            check(receipt.Format() == "none", "Unrelated events cannot fabricate a taskbar gesture receipt before mouse-down");
            var cached = Evidence();
            receipt.Begin(true, true, true, true, true, true, true, false, Int32.MaxValue, cached);
            string before = receipt.Format(); cached.Stage = TaskbarTargets.DiagnosticStage.Preview; cached.ShellProof = TaskbarTargets.ShellProofOutcome.ReadError;
            check(receipt.Format() == before && before.Contains("age=9999") && !before.Contains(PrivateMarker),
                "Mouse-down freezes safe cached evidence rather than retaining a mutable reader object");
            var fresh = Evidence(); receipt.Probe(fresh, true, Int32.MaxValue, true, true, true); receipt.Verified(true);
            before = receipt.Format(); fresh.ElapsedMilliseconds = -1; fresh.ShellProof = TaskbarTargets.ShellProofOutcome.ReaderTimeout;
            check(receipt.Format() == before && before.Contains("windows=9999") && before.Contains("verified=1"),
                "Post-release evidence is copied and its count bounded independently of later provider changes");
            receipt.Complete(TaskbarGestureRoute.NativeMinimize, true, false); string terminal = receipt.Format();
            receipt.Stopped(); receipt.Waiting(TaskbarGestureRoute.Cancelled); receipt.Direct(TaskbarDirectDecision.NoTarget);
            receipt.Cache(false, false, false, false, 0, null); receipt.DownContext(false, true);
            receipt.Probe(null, false, 0, false, false, false); receipt.Verified(false);
            receipt.Complete(TaskbarGestureRoute.Cancelled, false, true);
            check(receipt.Format() == terminal && terminal.Contains("route=NativeMinimize") && terminal.Contains("terminal=1"),
                "Stop, stale callbacks and later non-taskbar activity cannot overwrite a completed native-click receipt");
            receipt.Begin(false, false, false, false, false, false, false, true, -1, null);
            textReset(check, receipt.Format());
            receipt.Direct((TaskbarDirectDecision)Int32.MaxValue);
            receipt.Complete((TaskbarGestureRoute)(-1), false, false);
            check(receipt.Format().Contains("direct=Unknown route=Unknown") && receipt.Format().Length < 1500,
                "Unexpected route and decision enums format as bounded unknown diagnostics");
        }

        static void textReset(Action<bool, string> check, string text)
        {
            check(text.Contains("seq=2 bar=Secondary cache=0 age=0") && text.Contains("route=Down verified=-1") &&
                text.Contains("moved=0 replayed=0 stopped=0 terminal=0 cached[none] fresh[none]"),
                "Only a new taskbar mouse-down clears terminal state and begins a separate gesture receipt");
        }

        static void HookReceipt(Action<bool, string> check)
        {
            var hook = new TaskbarHookDiagnostics();
            hook.Record(true, true, TaskbarHookRoot.Primary, 1000);
            hook.Record(true, true, TaskbarHookRoot.ShellOther, 1100);
            hook.Record(true, true, TaskbarHookRoot.App, 1200);
            string text = hook.Format(1300, 1000);
            check(text.Contains("primaryLeft=1") && text.Contains("appLeft=1") &&
                text.Contains("lastDownAge=100 recognizedAge=300 shellOtherAge=200 shellOtherKind=ShellOther"),
                "Clicking an ordinary Copy diagnostics button preserves the preceding recognized and shell-other hook observations");
            hook.Record(false, false, TaskbarHookRoot.Secondary, 1350);
            text = hook.Format(1400, 1000);
            check(text.Contains("injectedDown=1") && text.Contains("secondaryLeft=0") && text.Contains("recognizedAge=400"),
                "Non-left input is counted without inventing a recognized taskbar left click");
            for (int index = 0; index < 10010; index++) hook.Record(true, true, TaskbarHookRoot.Primary, 1500);
            text = hook.Format(Int64.MaxValue, 1000);
            check(text.Contains("physicalDown=9999") && text.Contains("primaryLeft=9999") && text.Contains("recognizedAge=9999") && text.Length < 400,
                "Long sessions saturate counters and diagnostic ages instead of growing unbounded receipts");
            check(hook.Format(1400, 1000).Contains("recognizedAge=-1") && hook.Format(1600, 0).Contains("recognizedAge=-1"),
                "Backward or unavailable hook clocks report unknown age rather than misleading fresh evidence");
        }
    }
}
